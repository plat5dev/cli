package cmd

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"

	"github.com/plat5dev/cli/internal/plat5yml"
	"github.com/spf13/cobra"
	"gopkg.in/yaml.v3"
)

var routesCmd = &cobra.Command{
	Use:   "routes",
	Short: "Identity's and audit's generated routes",
}

var routesGenerateCmd = &cobra.Command{
	Use:   "generate [plat5.yml]",
	Short: "Write routes/identity.yml and routes/audit.yml from plat5.yml's kinds",
	Long: `Write routes/identity.yml and routes/audit.yml from plat5.yml's kinds, and add
them to plat5.yml's services if they're missing. The control plane generates
them (POST /catalog), so a kind not yet applied gets its routes in the same apply.

Overwrites those two files: git shows any hand edits it replaced.`,
	Args: cobra.MaximumNArgs(1),
	RunE: runRoutesGenerate,
}

func init() {
	routesCmd.AddCommand(routesGenerateCmd)
}

// generatedFiles are the routes files routes generate writes, by service.
var generatedFiles = []struct{ service, file string }{
	{"identity", "routes/identity.yml"},
	{"audit", "routes/audit.yml"},
}

const generatedHeader = "# Generated by plat5 routes generate from plat5.yml's kinds. Edit it like any\n# routes file; generating again overwrites it.\n"

func runRoutesGenerate(cmd *cobra.Command, args []string) error {
	path := configPath(args)
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	var top map[string]any
	if err := doc.Decode(&top); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if top["kinds"] == nil {
		return fmt.Errorf("%s has no kinds", path)
	}
	services, err := configClient().Catalog(top["kinds"])
	if err != nil {
		return explain(&plat5yml.Config{Path: path}, err)
	}

	dir := filepath.Dir(path)
	if err := os.MkdirAll(filepath.Join(dir, "routes"), 0o755); err != nil {
		return err
	}
	listed, err := plat5yml.ServiceFiles(top, filepath.Base(path))
	if err != nil {
		return err
	}
	var added []string
	for _, g := range generatedFiles {
		svc, ok := services[g.service]
		if !ok {
			return fmt.Errorf("the control plane generated no %s routes", g.service)
		}
		if err := plat5yml.WriteYAML(filepath.Join(dir, g.file), map[string]any{g.service: svc}, generatedHeader); err != nil {
			return err
		}
		fmt.Printf("  wrote %s\n", g.file)
		if !contains(listed, g.file) {
			added = append(added, g.file)
		}
	}
	if len(added) == 0 {
		return nil
	}
	if err := addServices(&doc, added); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return err
	}
	if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
		return err
	}
	for _, f := range added {
		fmt.Printf("  added %s to %s's services\n", f, filepath.Base(path))
	}
	return nil
}

// addServices appends routes files to plat5.yml's services list, keeping the
// rest of the file and its comments.
func addServices(doc *yaml.Node, files []string) error {
	if len(doc.Content) == 0 || doc.Content[0].Kind != yaml.MappingNode {
		return fmt.Errorf("must be a mapping")
	}
	top := doc.Content[0]
	var list *yaml.Node
	for i := 0; i+1 < len(top.Content); i += 2 {
		if top.Content[i].Value == "services" {
			list = top.Content[i+1]
		}
	}
	if list == nil {
		list = &yaml.Node{Kind: yaml.SequenceNode}
		top.Content = append(top.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: "services"}, list)
	}
	if list.Kind != yaml.SequenceNode {
		return fmt.Errorf("services must be a list of routes files")
	}
	if len(list.Content) == 0 {
		list.Style = 0 // block, not []
	}
	for _, f := range files {
		list.Content = append(list.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: f})
	}
	return nil
}
